def fix_file(path):
    p = Path(path)
    text = p.read_text(encoding="utf-8")
    if text.startswith("---\n"):
        parts = text.split("---\n", 2)
        fm_text = parts[1]
        body = parts[2]
    else:
        fm_text = ""
        body = text
    
    fm = yaml.safe_load(fm_text) or {}
    file_id = fm.get("id", p.stem)
    c = contents.get(file_id)
    if not c:
        print(f"SKIP: no content for {file_id}")
        return
    
    fm["status"] = "enriched"
    if isinstance(fm.get("created_at"), str) and " enriched" in fm["created_at"]:
        fm["created_at"] = fm["created_at"].replace(" enriched", "").strip()
    if "updated_at" not in fm:
        fm["updated_at"] = "2026-06-29"
    
    ev_rows = "\n".join([f"| {a} | {b} | {c2} |" for a, b, c2 in c["evidence"]])
    evidence_section = f"""## 关键证据

| 证据点 | 来源 | 可检验性 |
|:---|:---|:---|
{ev_rows}"""
    
    scenarios = "\n".join([f"- {s}" for s in c["scenarios"]])
    lessons = "\n".join([f"- {l}" for l in c["lessons"]])
    fail_rows = "\n".join([f"| **{a}** | {b} | {c2} |" for a, b, c2 in c["failures"]])
    
    new_tail = f"""

## 可迁移场景

{scenarios}

## 教训

{lessons}

## 失败模式

| 失败模式 | 症状 | 修复 |
|:---|:---|:---|
{fail_rows}
"""
    
    new_body = re.sub(
        r"## 关键证据.*?$",
        evidence_section + new_tail,
        body,
        flags=re.DOTALL,
    )
    
    new_fm = yaml.safe_dump(fm, sort_keys=False, allow_unicode=True)
    new_text = f"---\n{new_fm}---\n{new_body}"
    p.write_text(new_text, encoding="utf-8")
    print(f"FIXED: {file_id}")

for f in files:
    fix_file(f)
