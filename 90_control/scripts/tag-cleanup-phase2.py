changed = 0
removed = 0
mapped = 0
unmapped = Counter()

for root, dirs, files in os.walk(base):
    for f in files:
        if not f.endswith('.md'):
            continue
        path = os.path.join(root, f)
        p = Path(path)
        with open(path, 'r', encoding='utf-8', errors='ignore') as fh:
            text = fh.read()
        if not text.startswith('---\n'):
            continue
        end = text.find('\n---\n', 4)
        if end == -1:
            continue
        try:
            fm = yaml.safe_load(text[4:end])
            if not isinstance(fm, dict):
                continue
            old_tags = fm.get('tags', []) or []
            new_tags = []
            modified = False
            for t in old_tags:
                if t is None or str(t).strip() == '':
                    removed += 1
                    modified = True
                    continue
                t = str(t).strip()
                if t in extra_mapping:
                    repl = extra_mapping[t]
                    if repl:
                        new_tags.extend(repl)
                    removed += 1
                    mapped += len(repl)
                    modified = True
                elif not t.startswith('#'):
                    removed += 1
                    unmapped[t] += 1
                    modified = True
                else:
                    new_tags.append(t)
            if modified:
                seen = set()
                final = []
                for t in new_tags:
                    if t not in seen:
                        seen.add(t)
                        final.append(t)
                fm['tags'] = final
                new_fm = yaml.dump(fm, default_flow_style=False, allow_unicode=True, sort_keys=False).strip()
                p.write_text('---\n' + new_fm + '\n---\n' + text[end+5:], encoding='utf-8')
                changed += 1
        except Exception as e:
            pass

print(f'Changed files: {changed}')
print(f'Removed/mapped unqualified tags: {removed}')
print(f'New mapped tags added: {mapped}')
print(f'Unmapped invalid tags: {len(unmapped)}')
for t, c in unmapped.most_common(20):
    print(f'  {t}: {c}')
